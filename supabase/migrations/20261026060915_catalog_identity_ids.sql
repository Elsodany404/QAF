-- The admin "Add product" form inserts products, options and option values
-- without an id, but these tables were created with plain id columns (their
-- rows were imported with explicit ids), so every insert failed with
-- "null value in column id". Give them identity ids that continue after the
-- existing rows, like Order, OrderItem and ProductOptions.
DO $$
DECLARE
  t text;
  next_id bigint;
BEGIN
  FOREACH t IN ARRAY ARRAY['Product', 'Options', 'OptionValues'] LOOP
    EXECUTE format('SELECT COALESCE(MAX(id), 0) + 1 FROM public.%I', t)
      INTO next_id;
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (START WITH %s)',
      t,
      next_id
    );
  END LOOP;
END $$;
